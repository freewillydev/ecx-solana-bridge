CREATE FUNCTION trg_record_operating_cost() RETURNS trigger LANGUAGE plpgsql AS $body$
BEGIN IF NEW.account='operating' AND NEW.delta<0 THEN UPDATE operating_clock SET last_time=GREATEST(last_time,floor(extract(epoch FROM clock_timestamp()))::bigint); INSERT INTO operating_costs(posting_id,recorded_at) SELECT NEW.id,last_time FROM operating_clock; END IF; RETURN NEW; END
$body$;
CREATE TRIGGER record_operating_cost AFTER INSERT ON postings FOR EACH ROW EXECUTE FUNCTION trg_record_operating_cost();

