CREATE FUNCTION bridge_json_valid(value text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE STRICT AS $$ BEGIN PERFORM value::json; RETURN true; EXCEPTION WHEN invalid_text_representation THEN RETURN false; END $$;

CREATE TABLE orders(id TEXT PRIMARY KEY, capability_hash TEXT NOT NULL, idempotency_key TEXT NOT NULL, request_hash TEXT NOT NULL, request_json TEXT NOT NULL, quote_json TEXT NOT NULL, policy_json TEXT NOT NULL, status TEXT NOT NULL, deadline BIGINT NOT NULL, grace_deadline BIGINT NOT NULL, instruction TEXT UNIQUE, instruction_sequence BIGINT, payout_tx TEXT, instruction_issued BIGINT NOT NULL DEFAULT 0 CHECK(instruction_issued IN(0,1)), UNIQUE(capability_hash,idempotency_key));

CREATE TABLE events(id TEXT PRIMARY KEY, description TEXT NOT NULL);

CREATE TABLE checkpoints(chain TEXT PRIMARY KEY, anchor TEXT NOT NULL);

CREATE TABLE audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, action TEXT NOT NULL, detail TEXT NOT NULL);

CREATE TABLE deployment(singleton BIGINT PRIMARY KEY CHECK(singleton=1), schema_version BIGINT NOT NULL CHECK(schema_version>=1), fingerprint TEXT NOT NULL, critical_sequence BIGINT NOT NULL DEFAULT 0, backup_sequence BIGINT NOT NULL DEFAULT 0, paused BIGINT NOT NULL DEFAULT 1 CHECK(paused IN(0,1)), pause_reason TEXT NOT NULL DEFAULT 'initialization');

CREATE TABLE observation_evidence(hash TEXT PRIMARY KEY, chain TEXT NOT NULL, event_id TEXT NOT NULL, evidence_json TEXT NOT NULL);

CREATE TABLE scan_origins(chain TEXT PRIMARY KEY CHECK(chain IN('Native','Solana','SolanaOperating')), anchor TEXT NOT NULL);

CREATE TABLE scan_health(chain TEXT PRIMARY KEY CHECK(chain IN('Native','Solana','SolanaOperating')), last_success BIGINT, last_error TEXT, checked_at BIGINT NOT NULL);

CREATE TABLE operating_clock(singleton BIGINT PRIMARY KEY CHECK(singleton=1), last_time BIGINT NOT NULL CHECK(last_time>=0));

CREATE TABLE custody_check(singleton BIGINT PRIMARY KEY CHECK(singleton=1), revision BIGINT NOT NULL DEFAULT 0 CHECK(revision>=0), checked_revision BIGINT, checked_at BIGINT, last_error TEXT, report_json TEXT);

CREATE TABLE postings(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id TEXT NOT NULL REFERENCES events(id), asset TEXT NOT NULL CHECK(asset IN('Native','Wrapped','Sol')), account TEXT NOT NULL, delta BIGINT NOT NULL CHECK(delta<>0));

CREATE TABLE reservations(order_id TEXT PRIMARY KEY REFERENCES orders(id), asset TEXT NOT NULL, amount BIGINT NOT NULL CHECK(amount>0), phase TEXT NOT NULL CHECK(phase IN('quote','obligation','payment','released')));

CREATE TABLE deposits(id TEXT PRIMARY KEY, order_id TEXT REFERENCES orders(id), asset TEXT NOT NULL, amount BIGINT NOT NULL CHECK(amount>0), anchor TEXT NOT NULL, first_seen BIGINT NOT NULL, confirmations BIGINT NOT NULL CHECK(confirmations>=0), eligible BIGINT NOT NULL CHECK(eligible IN(0,1)), allocated BIGINT NOT NULL DEFAULT 0 CHECK(allocated IN(0,1)), state TEXT NOT NULL DEFAULT 'observed');

CREATE TABLE hints(order_id TEXT NOT NULL REFERENCES orders(id), signature TEXT NOT NULL, PRIMARY KEY(order_id,signature));

CREATE TABLE chain_events(chain TEXT NOT NULL CHECK(chain IN('Native','Solana','SolanaOperating')), event_id TEXT NOT NULL, kind TEXT NOT NULL, anchor TEXT NOT NULL, evidence_hash TEXT NOT NULL REFERENCES observation_evidence(hash), first_seen BIGINT NOT NULL, last_seen BIGINT NOT NULL, needs_review BIGINT NOT NULL CHECK(needs_review IN(0,1)), PRIMARY KEY(chain,event_id));

CREATE TABLE order_cost_limits(order_id TEXT PRIMARY KEY REFERENCES orders(id), native_fee BIGINT NOT NULL CHECK(native_fee>0), solana_fee BIGINT NOT NULL CHECK(solana_fee>0), solana_rent BIGINT NOT NULL CHECK(solana_rent>=0));

CREATE TABLE native_allocations(order_id TEXT PRIMARY KEY REFERENCES orders(id), label TEXT NOT NULL UNIQUE, critical_sequence BIGINT NOT NULL CHECK(critical_sequence>0));

CREATE TABLE obligations(id TEXT PRIMARY KEY, order_id TEXT NOT NULL REFERENCES orders(id), deposit_id TEXT NOT NULL REFERENCES deposits(id), kind TEXT NOT NULL CHECK(kind IN('conversion','refund')), asset TEXT NOT NULL, amount BIGINT NOT NULL CHECK(amount>0), recipient TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN('ready','paying','paid','review','cancelled')));

CREATE TABLE treasury_allocations(deposit_id TEXT PRIMARY KEY REFERENCES deposits(id), allocation_json TEXT NOT NULL, proof_json TEXT NOT NULL, critical_sequence BIGINT NOT NULL);

CREATE TABLE treasury_spends(chain TEXT NOT NULL, event_id TEXT NOT NULL, anchor TEXT NOT NULL, economic_json TEXT NOT NULL, proof_json TEXT NOT NULL, critical_sequence BIGINT NOT NULL, PRIMARY KEY(chain,event_id), FOREIGN KEY(chain,event_id) REFERENCES chain_events(chain,event_id));

CREATE TABLE operating_costs(posting_id BIGINT PRIMARY KEY REFERENCES postings(id), recorded_at BIGINT NOT NULL CHECK(recorded_at>=0));

CREATE TABLE operating_reservations(order_id TEXT NOT NULL REFERENCES order_cost_limits(order_id), kind TEXT NOT NULL CHECK(kind IN('conversion','refund')), asset TEXT NOT NULL CHECK(asset IN('Native','Sol')), amount BIGINT NOT NULL CHECK(amount>0), phase TEXT NOT NULL CHECK(phase IN('quote','obligation','transferred','released')), PRIMARY KEY(order_id,kind));

CREATE TABLE source_recoveries(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, deposit_id TEXT NOT NULL REFERENCES deposits(id), state TEXT NOT NULL CHECK(state IN('pending','missing','restored','unavailable')), shortfall BIGINT NOT NULL CHECK(shortfall>=0), evidence_json TEXT NOT NULL CHECK(bridge_json_valid(evidence_json) AND length(evidence_json)<=16384), critical_sequence BIGINT NOT NULL UNIQUE CHECK(critical_sequence>0));

CREATE TABLE intents(id TEXT PRIMARY KEY, obligation_id TEXT NOT NULL UNIQUE REFERENCES obligations(id), chain TEXT NOT NULL CHECK(chain IN('Native','Solana')), common_input TEXT, resolved BIGINT NOT NULL DEFAULT 0 CHECK(resolved IN(0,1)));

CREATE TABLE source_recovery_approvals(obligation_id TEXT NOT NULL REFERENCES obligations(id), restoration_sequence BIGINT NOT NULL REFERENCES source_recoveries(critical_sequence), loss_sequence BIGINT NOT NULL REFERENCES source_recoveries(critical_sequence), prior_status TEXT NOT NULL CHECK(prior_status IN('ready','paying')), work_hash TEXT NOT NULL CHECK(length(work_hash)=64), reason TEXT NOT NULL CHECK(length(trim(reason))>0 AND length(reason)<=512), proof_json TEXT NOT NULL CHECK(bridge_json_valid(proof_json) AND length(proof_json)<=32768), critical_sequence BIGINT NOT NULL UNIQUE CHECK(critical_sequence>restoration_sequence), PRIMARY KEY(obligation_id,restoration_sequence));

CREATE TABLE source_loss_covers(critical_sequence BIGINT PRIMARY KEY, deposit_id TEXT NOT NULL REFERENCES deposits(id), recovery_sequence BIGINT NOT NULL UNIQUE REFERENCES source_recoveries(critical_sequence), amount BIGINT NOT NULL CHECK(amount>0), float_amount BIGINT NOT NULL CHECK(float_amount>=0 AND float_amount<=amount), earned_amount BIGINT NOT NULL CHECK(earned_amount=amount-float_amount), reason TEXT NOT NULL CHECK(length(trim(reason))>0 AND length(reason)<=512), proof_json TEXT NOT NULL CHECK(bridge_json_valid(proof_json) AND length(proof_json)<=32768), CHECK(critical_sequence>recovery_sequence));

CREATE TABLE attempts(txid TEXT PRIMARY KEY, intent_id TEXT NOT NULL REFERENCES intents(id), signed_bytes TEXT NOT NULL, policy_json TEXT NOT NULL, fee_limit BIGINT NOT NULL CHECK(fee_limit>=0), state TEXT NOT NULL CHECK(state IN('signed','broadcast_intent','settled','failed','review')), critical_sequence BIGINT, observation_json TEXT, preparation_generation BIGINT NOT NULL DEFAULT 0 CHECK(preparation_generation>=0));

CREATE TABLE fee_reservations(intent_id TEXT PRIMARY KEY REFERENCES intents(id), asset TEXT NOT NULL, amount BIGINT NOT NULL CHECK(amount>=0), released BIGINT NOT NULL DEFAULT 0 CHECK(released IN(0,1)));

CREATE TABLE source_loss_returns(cover_sequence BIGINT PRIMARY KEY REFERENCES source_loss_covers(critical_sequence), recovery_sequence BIGINT NOT NULL REFERENCES source_recoveries(critical_sequence), CHECK(recovery_sequence>cover_sequence));

CREATE TABLE solana_expiries(txid TEXT PRIMARY KEY REFERENCES attempts(txid), proof_json TEXT NOT NULL, critical_sequence BIGINT NOT NULL);

CREATE TABLE native_payment_recoveries(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, txid TEXT NOT NULL REFERENCES attempts(txid), previous_observation TEXT NOT NULL CHECK(bridge_json_valid(previous_observation) AND length(previous_observation)<=32768), state TEXT NOT NULL CHECK(state IN('confirming','unavailable','reconfirmed')), observation_json TEXT NOT NULL CHECK(bridge_json_valid(observation_json) AND length(observation_json)<=32768), critical_sequence BIGINT NOT NULL UNIQUE CHECK(critical_sequence>0));

CREATE TABLE native_replacement_drafts(critical_sequence BIGINT PRIMARY KEY CHECK(critical_sequence>0), parent_txid TEXT NOT NULL REFERENCES attempts(txid), fee BIGINT NOT NULL CHECK(fee>0), draft_json TEXT NOT NULL CHECK(bridge_json_valid(draft_json) AND length(draft_json)<=200000), work_hash TEXT NOT NULL CHECK(length(work_hash)=64), reason TEXT NOT NULL CHECK(length(trim(reason))>0 AND length(reason)<=512), proof_json TEXT NOT NULL CHECK(bridge_json_valid(proof_json) AND length(proof_json)<=32768), UNIQUE(parent_txid,fee,reason));

CREATE TABLE native_winner_changes(critical_sequence BIGINT PRIMARY KEY CHECK(critical_sequence>0), previous_txid TEXT NOT NULL REFERENCES attempts(txid), winner_txid TEXT NOT NULL REFERENCES attempts(txid), previous_observation TEXT NOT NULL CHECK(bridge_json_valid(previous_observation) AND length(previous_observation)<=32768), observation_json TEXT NOT NULL CHECK(bridge_json_valid(observation_json) AND length(observation_json)<=32768), evidence_hash TEXT NOT NULL REFERENCES observation_evidence(hash), fee_delta BIGINT NOT NULL CHECK(fee_delta<>0), CHECK(previous_txid<>winner_txid));

CREATE TABLE preparations(intent_id TEXT NOT NULL REFERENCES intents(id), generation BIGINT NOT NULL CHECK(generation>=0), policy_json TEXT NOT NULL, draft_json TEXT, retired_txid TEXT UNIQUE REFERENCES solana_expiries(txid), cancelled BIGINT NOT NULL DEFAULT 0 CHECK(cancelled IN(0,1)), PRIMARY KEY(intent_id,generation));

CREATE TABLE solana_retry_approvals(expired_txid TEXT PRIMARY KEY REFERENCES solana_expiries(txid), reason TEXT NOT NULL, proof_json TEXT NOT NULL, critical_sequence BIGINT NOT NULL);

CREATE TABLE native_replacement_cancellations(draft_sequence BIGINT PRIMARY KEY REFERENCES native_replacement_drafts(critical_sequence), reason TEXT NOT NULL CHECK(length(trim(reason))>0 AND length(reason)<=512), critical_sequence BIGINT NOT NULL UNIQUE CHECK(critical_sequence>draft_sequence));

CREATE TABLE native_replacement_members(draft_sequence BIGINT PRIMARY KEY REFERENCES native_replacement_drafts(critical_sequence), txid TEXT NOT NULL UNIQUE REFERENCES attempts(txid), critical_sequence BIGINT NOT NULL UNIQUE CHECK(critical_sequence>draft_sequence));

CREATE TABLE preparation_cancellations(intent_id TEXT NOT NULL, generation BIGINT NOT NULL, reason TEXT NOT NULL, cleanup_json TEXT NOT NULL, critical_sequence BIGINT NOT NULL CHECK(critical_sequence>0), completed BIGINT NOT NULL DEFAULT 0 CHECK(completed IN(0,1)), PRIMARY KEY(intent_id,generation), FOREIGN KEY(intent_id,generation) REFERENCES preparations(intent_id,generation));

CREATE INDEX posting_balance ON postings(asset,account);

CREATE UNIQUE INDEX one_conversion ON obligations(order_id) WHERE kind='conversion';

CREATE UNIQUE INDEX one_unresolved_chain_intent ON intents(chain) WHERE resolved=0;

CREATE UNIQUE INDEX one_active_deposit_allocation ON obligations(deposit_id) WHERE status<>'cancelled';

CREATE INDEX chain_event_review ON chain_events(chain,needs_review,kind);

CREATE INDEX operating_cost_time ON operating_costs(recorded_at);

CREATE UNIQUE INDEX one_active_preparation ON preparations(intent_id) WHERE retired_txid IS NULL AND cancelled=0;

CREATE INDEX native_payment_recovery_latest ON native_payment_recoveries(txid,id);

CREATE INDEX source_recovery_latest ON source_recoveries(deposit_id,id);

CREATE VIEW source_recovery_state AS SELECT r.* FROM source_recoveries r WHERE r.id=(SELECT MAX(p.id) FROM source_recoveries p WHERE p.deposit_id=r.deposit_id);

CREATE INDEX source_loss_deposit ON source_loss_covers(deposit_id);

CREATE VIEW active_source_loss_covers AS SELECT f.* FROM source_loss_covers f WHERE NOT EXISTS(SELECT 1 FROM source_loss_returns r WHERE r.cover_sequence=f.critical_sequence);

CREATE VIEW proven_source_losses AS SELECT d.id AS deposit_id FROM deposits d JOIN source_recovery_state r ON r.deposit_id=d.id WHERE d.asset='Native' AND d.eligible=0 AND r.state='missing' AND r.shortfall=d.amount;

CREATE VIEW accounted_source_losses AS SELECT f.deposit_id FROM active_source_loss_covers f JOIN source_recovery_state r ON r.deposit_id=f.deposit_id JOIN deposits d ON d.id=f.deposit_id WHERE d.asset='Native' AND d.eligible=0 AND r.state='missing' AND r.shortfall=d.amount AND f.amount=d.amount;

CREATE UNIQUE INDEX one_settled_payment_per_intent ON attempts(intent_id) WHERE state='settled';

CREATE INDEX native_winner_change_history ON native_winner_changes(winner_txid,critical_sequence);

CREATE VIEW native_payment_recovery_state AS SELECT r.* FROM native_payment_recoveries r JOIN attempts a ON a.txid=r.txid WHERE a.state='settled' AND r.id=(SELECT MAX(p.id) FROM native_payment_recoveries p WHERE p.txid=r.txid) AND r.critical_sequence>COALESCE((SELECT MAX(w.critical_sequence) FROM native_winner_changes w WHERE w.winner_txid=r.txid),0);

CREATE FUNCTION trg_immutable_order() RETURNS trigger LANGUAGE plpgsql AS $body$
BEGIN IF (NEW.id IS DISTINCT FROM OLD.id OR NEW.capability_hash IS DISTINCT FROM OLD.capability_hash OR NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key OR NEW.request_hash IS DISTINCT FROM OLD.request_hash OR NEW.request_json IS DISTINCT FROM OLD.request_json OR NEW.quote_json IS DISTINCT FROM OLD.quote_json OR NEW.policy_json IS DISTINCT FROM OLD.policy_json OR NEW.deadline IS DISTINCT FROM OLD.deadline OR NEW.grace_deadline IS DISTINCT FROM OLD.grace_deadline) THEN RAISE EXCEPTION 'immutable_order' USING ERRCODE='23514'; END IF; RETURN NEW; END
$body$;
